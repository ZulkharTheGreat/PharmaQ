import { z } from "zod";
export const objectSchema = z.object({
  id: z.string(),
  kind: z.enum(["product", "batch", "material", "equipment", "area"]),
  name: z.string().trim().min(1, "Укажите объект"),
  batch: z.string().default(""),
  code: z.string().default(""),
  supplierBatch: z.string().default(""),
  quantity: z.string().default(""),
  order: z.string().default(""),
  productionStage: z.string().default(""),
});
export const registerSchema = z.object({
  title: z.string().trim().min(1, "Укажите название").max(300),
  description: z.string().trim().min(1, "Опишите факты"),
  detectedAt: z.string(),
  department: z.string().trim().min(1, "Укажите подразделение"),
  line: z.string().trim().min(1, "Укажите участок"),
  area: z.string().default(""),
  place: z.string().default(""),
  detector: z.string().default(""),
  expected: z.string().default(""),
  actual: z.string().default(""),
  immediateActions: z.string().default(""),
  impact: z.string().default(""),
  safety: z.string().default(""),
  amount: z.string().default(""),
  objects: z.array(objectSchema).default([]),
  coordinatorId: z.string().optional(),
  relatedCaseId: z.string().optional(),
});
export const assessmentSchema = z.object({
  objects: z.array(objectSchema).optional(),
  severity: z.enum(["low", "medium", "high", "critical"]),
  reason: z.string(),
  category: z.string().default(""),
  impact: z.string().default(""),
  safety: z.string().default(""),
  scope: z.string(),
  participants: z.array(z.string()),
  leadId: z.string(),
  due: z.string(),
  revisionReason: z.string().default(""),
});
export const investigationSchema = z.object({
  facts: z.string(),
  chronology: z.string().default(""),
  participants: z.array(z.string()),
  hypotheses: z.string(),
  evidence: z.string(),
  method: z.string(),
  why: z.array(z.string()).default([]),
  conclusion: z.string(),
  cause: z.string().default(""),
  confirmed: z.boolean(),
  uncertainty: z.string().default(""),
  revisionReason: z.string().default(""),
  revision: z.number().default(0),
});
const permitSchema = z.object({
  id: z.string(),
  scope: z.string(),
  zone: z.string(),
  people: z.string(),
  tools: z.string(),
  expiresAt: z.string(),
  reference: z.string(),
});
const contractorSchema = z.object({
  contractorId: z.string(),
  scope: z.string(),
  zone: z.string(),
  people: z.string(),
  tools: z.string(),
  requirements: z.array(z.string()),
  permits: z.array(permitSchema).default([]),
  approvedBy: z.string().optional(),
  approvedAt: z.string().optional(),
  approvalReason: z.string().optional(),
  calledAt: z.string().optional(),
  arrivedAt: z.string().optional(),
  events: z
    .array(
      z.object({
        type: z.string(),
        at: z.string(),
        recordedAt: z.string(),
        reason: z.string(),
        actorId: z.string(),
      }),
    )
    .default([]),
});
export const taskSchema = z.object({
  id: z.string(),
  measureId: z.string().default(""),
  kind: z.enum(["action", "effectiveness", "immediate", "clarification"]),
  title: z.string(),
  outcome: z.string(),
  ownerId: z.string(),
  performerId: z.string(),
  reviewerId: z.string(),
  due: z.string(),
  criteria: z.string(),
  requiredEvidence: z.string(),
  required: z.boolean().default(true),
  dependencies: z.array(z.string()).default([]),
  observationHours: z.number().default(0),
  notBefore: z.string().optional(),
  method: z.string().default(""),
  contractor: contractorSchema.optional(),
  cancelReason: z.string().optional(),
  relatedTaskId: z.string().optional(),
});
